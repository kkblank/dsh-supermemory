/**
 * 选出本轮整编要用的 system 提示（契约 §V12.12）。
 *
 * 三段可以叠加，顺序固定：主提示 → 冷启动 → 分批说明（分批放最后，它的「你只看到一部分」
 * 必须紧贴输出指令，否则容易被前面的内容稀释）。
 *
 * **冷启动的触发条件必须同时满足两条**：
 *   ① 盘上主题表为空（`topics.length === 0`）；
 *   ② 盘上条目里一个 `topic` 都没有（`hasAnyTopic === false`）。
 * 只看 ① 会在「主题表被手删了但条目还都带着 topic」时误触发，逼模型把已经分好的条目
 * 重新分类——那正是冷启动引导最该避免的破坏。
 *
 * 抽成纯函数是为了能直接测：这段判定原本会埋在 digest.js 的调用链里，只能靠跑真实整编反推。
 *
 * @param {{ topics?: unknown, hasAnyTopic?: unknown, batch?: unknown }} [input] - 判定输入。
 *   `topics` 是盘上主题表数组，`hasAnyTopic` 表示条目里是否已有 topic，`batch` 表示本轮是否分批。
 * @returns {string} 要交给模型的 system 提示。
 */
export function selectConsolidateSystemPrompt(input = {}) {
  const topicsEmpty = !Array.isArray(input.topics) || input.topics.length === 0
  const bootstrap = topicsEmpty && input.hasAnyTopic !== true
  const parts = [CONSOLIDATE_SYSTEM_PROMPT]
  if (bootstrap) parts.push(CONSOLIDATE_BOOTSTRAP_NOTE)
  if (input.batch === true) parts.push(CONSOLIDATE_BATCH_NOTE)
  return parts.join('\n\n')
}

